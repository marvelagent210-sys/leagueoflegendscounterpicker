/** Markdown reports committed next to each dataset, for people to review. */
import { TOP_LANE_MAX_LEVEL, statsAtLevel } from "../engine/stats";
import type { Champion } from "../engine/types";
import type { Reconciled } from "./gameFiles";
import type { Manifest } from "./manifest";

const fixed = (value: number, digits: number) => value.toFixed(digits);

export function level20Report(manifest: Manifest, champions: Champion[]): string {
  const level = TOP_LANE_MAX_LEVEL;
  const lines = [
    `# Base stats at level ${level} (patch ${manifest.patch})`,
    "",
    `Generated by \`npm run build:data\` from the League of Legends Wiki (${manifest.wiki.license}), with base stats`,
    "checked against the game files (see game-files.md). Base stats only: no abilities, items or stat budget.",
    "Regeneration is per 5 seconds.",
    "Attack time is the time between attacks; windup is the time from starting an attack to launching it.",
    "",
    "| Champion | Form | HP | HP regen | Resource | Resource regen | Resource type | AD | Attack speed | Attack time (s) | Windup (s) | Armor | Magic resist | Range | Move speed |",
    "|---|---|--:|--:|--:|--:|---|--:|--:|--:|--:|--:|--:|--:|--:|",
  ];
  for (const champion of champions) {
    for (const form of champion.forms) {
      const s = statsAtLevel(form.stats, level);
      const formLabel = champion.forms.length > 1 ? form.name : "";
      lines.push(
        `| ${champion.name} | ${formLabel} | ${fixed(s.hp, 1)} | ${fixed(s.hpRegen, 2)} | ${fixed(s.resource, 1)} | ` +
          `${fixed(s.resourceRegen, 2)} | ${champion.resource} | ${fixed(s.attackDamage, 1)} | ${fixed(s.attackSpeed, 3)} | ` +
          `${fixed(s.attackTime, 3)} | ${fixed(s.attackWindup, 3)} | ${fixed(s.armor, 1)} | ${fixed(s.magicResist, 1)} | ` +
          `${s.attackRange} | ${s.moveSpeed} |`,
      );
    }
  }
  return `${lines.join("\n")}\n`;
}

function formatValue(value: number | null): string {
  return value === null ? "–" : String(Number(value.toPrecision(6)));
}

export function gameFilesReport(manifest: Manifest, reconciled: Reconciled): string {
  const lines = [
    `# Wiki vs game files: base stats (patch ${manifest.patch})`,
    "",
    "Generated by `npm run build:data`. Base stats start from the League of Legends Wiki. When the",
    `game data files (CommunityDragon ${manifest.cdragon.version}) state a different value for a`,
    "champion's base form, the game value is used. Fields the game files leave out (the game omits",
    "values equal to its defaults) are not compared. Regeneration is per 5 seconds; resources are",
    "compared for mana and energy only.",
    "",
    "Data Dragon is not used for stats: in 16.20 it reports 0 attack damage per level for every champion.",
    "",
    `## Game values used (${reconciled.applied.length})`,
    "",
  ];
  if (reconciled.applied.length === 0) lines.push("None.");
  else {
    lines.push("| Form | Stat | Wiki | Game files (used) |", "|---|---|--:|--:|");
    for (const d of reconciled.applied) lines.push(`| ${d.form} | ${d.stat} | ${formatValue(d.wiki)} | ${formatValue(d.game)} |`);
  }
  const levelScaled = reconciled.entries.filter((entry) => entry.stats.windup.castTimeByLevel);
  if (levelScaled.length > 0) {
    lines.push("", "Level-scaled attack cast times from the game files:", "");
    for (const entry of levelScaled) {
      const c = entry.stats.windup.castTimeByLevel;
      if (!c) continue;
      lines.push(
        `- ${entry.name}: ${c.start} s at level 1 to ${c.end} s at level 18, ` +
          `${c.scalePastMaxLevel ? "still scaling" : "no further change"} at levels 19-20`,
      );
    }
  }
  lines.push("", `## Differences reported only (${reconciled.notApplied.length})`, "");
  if (reconciled.notApplied.length === 0) lines.push("None.");
  else {
    lines.push("| Form | Stat | Wiki (used) | Game files | Why not applied |", "|---|---|--:|--:|---|");
    for (const d of reconciled.notApplied) {
      lines.push(`| ${d.form} | ${d.stat} | ${formatValue(d.wiki)} | ${formatValue(d.game)} | ${d.reason} |`);
    }
  }
  return `${lines.join("\n")}\n`;
}
